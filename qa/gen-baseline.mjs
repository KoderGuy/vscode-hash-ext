/**
 * Baseline GENERATOR — an INDEPENDENT, explicit step.
 *
 * Run only via `npm run gen:baseline`. It is NOT invoked by `npm run qa`,
 * `npm run package`, or any other command. It writes a *candidate* to a
 * gitignored staging area and NEVER touches /baseline. QA never reads
 * staging — only committed data in /baseline is ever used to test.
 *
 * Workflow:
 *   1. (optional) edit baseline/test-strings.json   — the frozen inputs
 *   2. npm run gen:baseline                          — writes staging candidate
 *   3. review the candidate diff carefully
 *   4. npm run baseline:promote                      — copies it into /baseline
 *   5. git add baseline && git commit                — REQUIRED; QA refuses
 *                                                      uncommitted baselines
 *
 * Digests are computed with Node `crypto` directly — the ORACLE, independent
 * of the extension code under test. The KAT vectors (validated at the top of
 * every QA run) anchor that this oracle is itself correct.
 */
import * as crypto from 'crypto';
import { createRequire } from 'module';
import { fileURLToPath } from 'url';
import * as fs from 'fs';
import * as path from 'path';

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..');
const STAGING_DIR = path.join(here, '.staging-baseline');
const STAGING_FILE = path.join(STAGING_DIR, 'baseline.json');
const TEST_STRINGS = path.join(repoRoot, 'baseline', 'test-strings.json');

const { ALGORITHMS } = require(path.join(here, 'algorithms.cjs'));
const testStrings = JSON.parse(fs.readFileSync(TEST_STRINGS, 'utf8')).strings;

const available = new Set(crypto.getHashes());
const missing = ALGORITHMS.filter((a) => !available.has(a.cryptoName));
if (missing.length) {
  console.error(
    'Refusing to generate: algorithms unavailable in this Node/OpenSSL ' +
      `build: ${missing.map((a) => a.cryptoName).join(', ')}`,
  );
  process.exit(1);
}

const hashes = {};
for (const s of testStrings) {
  const perAlgo = {};
  for (const algo of ALGORITHMS) {
    const raw = crypto.createHash(algo.cryptoName).update(s.value, 'utf8').digest();
    perAlgo[algo.cryptoName] = {
      hex: raw.toString('hex'),
      base64: raw.toString('base64'),
    };
  }
  hashes[s.id] = perAlgo;
}

const baseline = {
  _comment:
    'FROZEN QA BASELINE CANDIDATE. Generated by qa/gen-baseline.mjs using ' +
    'Node crypto (the oracle, independent of the extension). hex = lowercase ' +
    'hex of the UTF-8 digest; base64 = standard base64 of the same raw ' +
    'digest bytes. This is a STAGING candidate: review it, run ' +
    '`npm run baseline:promote`, then `git add baseline && git commit`. QA ' +
    'only ever tests against the COMMITTED /baseline copy.',
  schema: 1,
  generatedBy: 'qa/gen-baseline.mjs',
  algorithms: ALGORITHMS.map((a) => ({
    id: a.id,
    cryptoName: a.cryptoName,
    label: a.label,
    legacy: !!a.legacy,
  })),
  strings: testStrings,
  hashes,
};

fs.mkdirSync(STAGING_DIR, { recursive: true });
fs.writeFileSync(STAGING_FILE, JSON.stringify(baseline, null, 2) + '\n', 'utf8');

console.log(
  `Wrote STAGING candidate: ${STAGING_FILE}\n` +
    `  ${testStrings.length} strings x ${ALGORITHMS.length} algorithms ` +
    `x {hex,base64} = ${testStrings.length * ALGORITHMS.length * 2} values\n\n` +
    'This is NOT yet used by QA. Next:\n' +
    '  1. Review the candidate above.\n' +
    '  2. npm run baseline:promote      (copies it into /baseline)\n' +
    '  3. git add baseline && git commit -m "update QA baseline"\n' +
    'QA refuses to run against an uncommitted baseline.',
);
